def readings(name):
    """-> danh sach cac chuoi Han-Viet co the (thuong 1, nhieu khi chu co nhieu am); chu la-tinh/so giu nguyen; None neu thieu chu."""
    outs = [""]
    for ch in name:
        if "一" <= ch <= "鿿":
            r = HANVIET.get(ch)
            if not r:
                return None
            outs = [o + (" " if o else "") + x for o in outs for x in r]
            if len(outs) > 64:
                outs = outs[:64]
        else:
            outs = [o + ch for o in outs]
    return outs
